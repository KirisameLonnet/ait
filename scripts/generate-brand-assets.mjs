const images = "apps/app/assets/images";
add(`${images}/icon.png`, await png(mobile, 1024, true));
add(`${images}/android-icon-foreground.png`, await png(adaptive, 1024));
add(`${images}/notification-icon.png`, await png(svg(bird(placements.icon, colors.surface)), 96));
add(`${images}/splash-icon.png`, await png(splash, 1024));
add(`${images}/splash-icon-dark.png`, await png(splashDark, 1024));
add(`${images}/favicon.png`, await png(favicon("light"), 48));
for (const scheme of ["light", "dark"]) {
  for (const status of ["idle", "running", "attention"]) {
    const name = `favicon-${scheme}${status === "idle" ? "" : `-${status}`}`;
    const source = favicon(scheme, status);
    add(`${images}/${name}.svg`, source);
    add(`${images}/${name}.png`, await png(source, 48));
  }
}
for (const [name, size] of [
  ["apple-touch-icon", 180],
  ["pwa-icon-192", 192],
  ["pwa-icon-512", 512],
]) {
  add(
    `apps/app/public/${name}.png`,
    await png(name === "apple-touch-icon" ? mobile : maskable, size, true),
  );
}

// Native folders are generated/ignored. Refresh an existing iOS prebuild explicitly;
// clean prebuilds consume app.config.js and the assets above automatically.
if (syncNative) {
  const ios = resolve(root, "apps/app/ios");
  let projects = [];
  try {
    projects = await readdir(ios, { withFileTypes: true });
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  for (const project of projects.filter((entry) => entry.isDirectory() && entry.name !== "Pods")) {
    const catalog = `apps/app/ios/${project.name}/Images.xcassets`;
    try {
      await access(resolve(root, catalog));
    } catch (error) {
      if (error.code === "ENOENT") continue;
      throw error;
    }
    add(`${catalog}/AppIcon.appiconset/App-Icon-1024x1024@1x.png`, await png(mobile, 1024, true));
    const contents = { images: [], info: { author: "xcode", version: 1 } };
    for (const scale of [1, 2, 3]) {
      for (const dark of [false, true]) {
        const filename = `image${dark ? "-dark" : ""}${scale === 1 ? "" : `@${scale}x`}.png`;
        add(
          `${catalog}/SplashScreenLogo.imageset/${filename}`,
          await png(dark ? splashDark : splash, 200 * scale),
        );
        contents.images.push({
          filename,
          idiom: "universal",
          scale: `${scale}x`,
          ...(dark ? { appearances: [{ appearance: "luminosity", value: "dark" }] } : {}),
        });
      }
    }
    add(
      `${catalog}/SplashScreenLogo.imageset/Contents.json`,
      `${JSON.stringify(contents, null, 2)}\n`,
    );
    const colorSet = JSON.parse(
      await readFile(resolve(root, `${catalog}/SplashScreenBackground.colorset/Contents.json`)),
    );
    for (const entry of colorSet.colors) {
      if (!entry.appearances?.some((appearance) => appearance.value === "dark")) {
        entry.color.components = {
          red: "0.980392",
          green: "0.980392",
          blue: "0.972549",
          alpha: "1.000000",
        };
      }
    }
    add(
      `${catalog}/SplashScreenBackground.colorset/Contents.json`,
      `${JSON.stringify(colorSet, null, 2)}\n`,
    );
  }
}

const stale = [];
for (const [path, expected] of outputs) {
  const absolute = resolve(root, path);
  if (check) {
    let actual;
    try {
      actual = await readFile(absolute);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (!actual?.equals(expected)) stale.push(path);
  } else {
    await mkdir(dirname(absolute), { recursive: true });
    await writeFile(absolute, expected);
  }
}
if (stale.length > 0) {
  console.error(`Stale brand assets; run npm run generate:icons:\n${stale.join("\n")}`);
  process.exitCode = 1;
} else {
  console.log(
    `${check ? "Verified" : "Generated"} ${outputs.size} AIT brand assets (${brand.version}).`,
  );
}
