const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const syncNative = process.argv.includes("--sync-native");
const brand = JSON.parse(await readFile(resolve(root, "apps/app/src/branding/ait-mark.json")));
const { colors, placements } = brand;
const outputs = new Map();

function svg(body, viewBox = "0 0 1024 1024", size = 1024) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="${viewBox}" role="img" aria-label="AIT"><!-- Generated by scripts/generate-brand-assets.mjs. -->${body}</svg>\n`;
}

function bird(transform = placements.icon, monochrome, small = false) {
  const paths = monochrome
    ? `<path d="${small ? brand.smallSilhouette : brand.silhouette}" fill="${monochrome}"/>`
    : brand.faces
        .map((d, i) => `<path d="${d}" fill="${i === 0 ? colors.primary : colors.secondary}"/>`)
        .join("");
  return `<g transform="${transform}">${paths}</g>`;
}

const tile = svg(
  `<rect x="48" y="48" width="928" height="928" rx="208" fill="${colors.canvas}" stroke="${colors.border}" stroke-width="2"/>${bird()}`,
);
// Full bleed, opaque square: the launcher supplies its own mask.
const mobile = svg(`<rect width="1024" height="1024" fill="${colors.canvas}"/>${bird()}`);
const maskable = svg(
  `<rect width="1024" height="1024" fill="${colors.canvas}"/>${bird(placements.maskable)}`,
);
// Both Android's adaptive safe circle and the PWA maskable safe circle retain every tip.
const adaptive = svg(bird(placements.adaptive));
const splash = svg(
  `${bird(placements.stackedMark)}<path d="${brand.wordmark}" transform="${placements.stackedWordmark}" fill="${colors.ink}"/>`,
);
const splashDark = svg(
  `${bird(placements.stackedMark)}<path d="${brand.wordmark}" transform="${placements.stackedWordmark}" fill="${colors.surface}"/>`,
);

async function png(source, size, opaque = false) {
  let pipeline = sharp(Buffer.from(source)).resize(size, size);
  if (opaque) pipeline = pipeline.flatten({ background: colors.canvas }).removeAlpha();
  return pipeline.png({ compressionLevel: 9 }).toBuffer();
}

function add(path, contents) {
  outputs.set(path, Buffer.isBuffer(contents) ? contents : Buffer.from(contents));
}

// PNG-backed ICO entries are supported by the Windows versions supported by Electron.
async function ico() {
  const sizes = [16, 24, 32, 48, 64, 128, 256];
  const images = await Promise.all(
    sizes.map((size) => png(size <= 32 ? favicon("light") : tile, size)),
  );
  const header = Buffer.alloc(6 + sizes.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(sizes.length, 4);
  let offset = header.length;
  sizes.forEach((size, i) => {
    const entry = 6 + i * 16;
    header[entry] = size === 256 ? 0 : size;
    header[entry + 1] = size === 256 ? 0 : size;
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(images[i].length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += images[i].length;
  });
  return Buffer.concat([header, ...images]);
}

async function icns() {
  const entries = [
    ["icp4", 16],
    ["icp5", 32],
    ["icp6", 64],
    ["ic07", 128],
    ["ic08", 256],
    ["ic09", 512],
    ["ic10", 1024],
    ["ic11", 32],
    ["ic12", 64],
    ["ic13", 256],
    ["ic14", 512],
  ];
  const chunks = await Promise.all(
    entries.map(async ([type, size]) => {
      const image = await png(size <= 32 ? favicon("light") : tile, size);
      const header = Buffer.alloc(8);
      header.write(type, 0, 4, "ascii");
      header.writeUInt32BE(image.length + 8, 4);
      return Buffer.concat([header, image]);
    }),
  );
  const header = Buffer.alloc(8);
  header.write("icns");
  header.writeUInt32BE(8 + chunks.reduce((sum, chunk) => sum + chunk.length, 0), 4);
  return Buffer.concat([header, ...chunks]);
}

function favicon(scheme, status = "idle") {
  const color = scheme === "dark" ? colors.secondary : colors.primary;
  const badge =
    status === "idle"
      ? ""
      : `<circle cx="26" cy="26" r="5" fill="${status === "running" ? "#3B82F6" : "#22C55E"}" stroke="${scheme === "dark" ? colors.ink : colors.canvas}" stroke-width="1.5"/>`;
  return svg(`${bird("translate(1 5) scale(0.04545)", color, true)}${badge}`, "0 0 32 32", 48);
}

